import { createHash } from 'crypto';
import { readFileSync } from 'fs';
import { describe, expect, it } from 'vitest';
import { EnhancedDatFormat } from '../../../src/storage/formats/EnhancedDatFormat';
import { FormatProvider } from '../../../src/storage/formats/FormatProvider';
import { QuetzalFormat } from '../../../src/storage/formats/QuetzalFormat';
import { Logger } from '../../../src/utils/log';
import { buildFixtureState } from '../../utils/saveFixtureState';

Logger.setLogToConsole(false);

/**
 * Saves written by 1.0.0-rc.1 (tests/fixtures/saves/rc1-state.*) must keep loading, and the same state must
 * keep serializing to the same bytes, so a save made with one release restores in the next. The fixtures were
 * generated by the rc.1 code from buildFixtureState(); expected.json is what rc.1 read back from them.
 */
const fixture = (name: string) => new URL(`../../fixtures/saves/${name}`, import.meta.url);
const expected = JSON.parse(readFileSync(fixture('rc1-state.expected.json'), 'utf8'));
const sha256 = (bytes: Uint8Array) => createHash('sha256').update(bytes).digest('hex');

describe.each([
  ['Quetzal', 'qzl', () => new QuetzalFormat() as FormatProvider],
  ['EnhancedDat', 'dat', () => new EnhancedDatFormat() as FormatProvider],
])('%s save compatibility with rc.1', (_name, extension, createFormat) => {
  const saved = readFileSync(fixture(`rc1-state.${extension}`));

  it('should write the same bytes rc.1 wrote for the same state', () => {
    const bytes = createFormat().serialize(buildFixtureState());

    expect(Buffer.from(bytes).equals(saved)).toBe(true);
  });

  it('should return plain bytes, not a Node Buffer', () => {
    const bytes = createFormat().serialize(buildFixtureState());

    expect(bytes).toBeInstanceOf(Uint8Array);
    expect(Buffer.isBuffer(bytes)).toBe(false);
  });

  // The same fixture, as a Buffer (what readFileSync returns) and as a plain Uint8Array (what fetch gives)
  it.each([
    ['a Buffer', () => saved],
    ['a plain Uint8Array', () => new Uint8Array(saved)],
  ])('should read the rc.1 save from %s', (_inputName, input) => {
    const state = buildFixtureState();
    const original = new Uint8Array(state.originalStory);

    const restored = createFormat().deserialize(input(), original);

    expect(restored.pc).toBe(expected[extension].pc);
    expect(restored.stack).toEqual(expected[extension].stack);
    expect(restored.callFrames).toEqual(expected[extension].callFrames);
    expect(sha256(restored.memory)).toBe(expected[extension].memorySha256);
    expect(sha256(restored.originalStory)).toBe(expected[extension].originalStorySha256);
    expect(Buffer.isBuffer(restored.memory)).toBe(false);
  });
});
